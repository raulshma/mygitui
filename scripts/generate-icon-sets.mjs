#!/usr/bin/env node
/**
 * Generates the per-library chrome-icon data modules consumed by
 * `src/lib/components/icons/library.svelte.ts`.
 *
 * Input:  src/lib/components/icons/sets/mapping.json — a hand-curated map of
 *         chrome-semantic icon name → per-library Iconify slug. The semantic
 *         name is the Material Symbols slug when one exists, otherwise the
 *         Lucide slug (lucide is the default set, so every semantic name MUST
 *         map there; the other libraries map only where a good equivalent
 *         exists — call sites fall back to lucide when a slug is absent).
 * Output: src/lib/components/icons/sets/generated/<set>.ts — one module per
 *         library, each exporting `Record<string, IconifyIcon>` keyed by
 *         semantic name. `material-symbols.ts` re-exports tree-shaken
 *         per-icon imports from `@ktibow/iconset-material-symbols` (the one
 *         installed Material Symbols source) instead of inlining bodies.
 *
 * Icon data is extracted from the `@iconify-json/<set>` packages, resolving
 * aliases through their `aliases` tables so either form works in the mapping.
 * The script is deterministic (sorted keys, stable formatting): re-running it
 * over an unchanged mapping rewrites identical files. It prints a coverage
 * report and exits non-zero when a required lucide slug cannot be resolved.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const mappingPath = resolve(repoRoot, "src/lib/components/icons/sets/mapping.json");
const outDir = resolve(repoRoot, "src/lib/components/icons/sets/generated");

/** Local Material Symbols package (per-icon ESM files: <slug>.js). */
const KTIBOW_DIR = join(repoRoot, "node_modules", "@ktibow", "iconset-material-symbols");

const SETS = [
	{ id: "lucide", pkg: "@iconify-json/lucide", constant: "LUCIDE_ICONS", required: true },
	{ id: "tabler", pkg: "@iconify-json/tabler", constant: "TABLER_ICONS" },
	{ id: "hugeicons", pkg: "@iconify-json/hugeicons", constant: "HUGEICONS_ICONS" },
	{ id: "phosphor", pkg: "@iconify-json/ph", constant: "PHOSPHOR_ICONS" },
	{ id: "ri", pkg: "@iconify-json/ri", constant: "RI_ICONS" },
];

/** Collects failures that should fail the run (lucide) vs. degrade (others). */
const missing = new Map(); // setId -> string[] (semantic names)

/** Resolves `name` in a collection, following (and merging) aliases. */
function resolveIcon(collection, name, seen = new Set()) {
	if (seen.has(name)) return null;
	seen.add(name);
	const icon = collection.icons?.[name];
	if (icon) return icon.hidden ? null : icon;
	const alias = collection.aliases?.[name];
	if (!alias) return null;
	const parent = resolveIcon(collection, alias.parent, seen);
	if (!parent || alias.hidden) return null;
	// The alias's own geometry overrides the parent's (Iconify format).
	return { ...parent, ...Object.fromEntries(
		["body", "width", "height", "left", "top"]
			.filter((key) => alias[key] !== undefined)
			.map((key) => [key, alias[key]]),
	) };
}

/** Extracts the IconifyIcon shape we pin, defaulting dims from the collection. */
function toIconData(icon, collection) {
	const data = {
		width: icon.width ?? collection.width ?? 24,
		height: icon.height ?? collection.height ?? 24,
	};
	if (icon.left) data.left = icon.left;
	if (icon.top) data.top = icon.top;
	data.body = icon.body;
	return data;
}

/** `arrow-back-rounded` -> `iconArrowBackRounded` (imports need identifiers). */
function importIdentifier(slug) {
	const camel = slug.replace(/-([a-z0-9])/g, (_, char) => char.toUpperCase());
	return `icon${camel[0].toUpperCase()}${camel.slice(1)}`;
}

function renderIconLiteral(data) {
	const parts = [`width: ${data.width}`, `height: ${data.height}`];
	if (data.left) parts.push(`left: ${data.left}`);
	if (data.top) parts.push(`top: ${data.top}`);
	parts.push(`body: ${JSON.stringify(data.body)}`);
	return `{ ${parts.join(", ")} }`;
}

/** Writes one `Record<string, IconifyIcon>` module for a @iconify-json set. */
function writeCollectionModule(set, semanticNames, mapping, collections) {
	const collection = collections[set.pkg];
	const resolved = [];
	const misses = [];
	for (const semantic of semanticNames) {
		const slug = mapping[semantic][set.id];
		if (!slug) {
			misses.push(semantic);
			continue;
		}
		const icon = resolveIcon(collection, slug);
		if (!icon) {
			// A dead slug is a mapping bug: loud even for optional sets.
			misses.push(`${semantic} (slug "${slug}" not found)`);
			continue;
		}
		resolved.push([semantic, renderIconLiteral(toIconData(icon, collection))]);
	}
	missing.set(set.id, misses);

	const lines = [
		`// Generated by scripts/generate-icon-sets.mjs — do not edit.`,
		`// Source: ${set.pkg}, slugs curated in ../mapping.json (keys are semantic names).`,
		`import type { IconifyIcon } from "@iconify/types";`,
		``,
		`export const ${set.constant}: Record<string, IconifyIcon> = {`,
		...resolved.map(([semantic, literal]) => `\t"${semantic}": ${literal},`),
		`};`,
		``,
	];
	writeFileSync(join(outDir, `${set.id}.ts`), lines.join("\n"), "utf8");
	return resolved.length;
}

/** Writes the Material Symbols module from per-icon static imports. */
function writeMaterialSymbolsModule(semanticNames, mapping) {
	const imports = [];
	const entries = [];
	const misses = [];
	for (const semantic of semanticNames) {
		// The semantic name is an ms slug by convention; per-entry overrides
		// cover the few cases where the best ms glyph uses a different name.
		const slug = mapping[semantic]["material-symbols"] ?? semantic;
		if (!existsSync(join(KTIBOW_DIR, `${slug}.js`))) {
			misses.push(semantic);
			continue;
		}
		const identifier = importIdentifier(slug);
		imports.push(`import ${identifier} from "@ktibow/iconset-material-symbols/${slug}";`);
		entries.push(`\t"${semantic}": ${identifier},`);
	}
	missing.set("material-symbols", misses);

	const lines = [
		`// Generated by scripts/generate-icon-sets.mjs — do not edit.`,
		`// Re-exports tree-shaken Material Symbols data keyed by semantic name`,
		`// (see ../mapping.json); per-icon imports keep the bundle minimal.`,
		`import type { IconifyIcon } from "@iconify/types";`,
		...imports.sort(),
		``,
		`export const MATERIAL_SYMBOLS_ICONS: Record<string, IconifyIcon> = {`,
		...entries,
		`};`,
		``,
	];
	writeFileSync(join(outDir, "material-symbols.ts"), lines.join("\n"), "utf8");
	return entries.length;
}

// ---------------------------------------------------------------------------
// Run
// ---------------------------------------------------------------------------

const mapping = JSON.parse(readFileSync(mappingPath, "utf8"));
const semanticNames = Object.keys(mapping).sort();

mkdirSync(outDir, { recursive: true });

const collections = {};
for (const set of SETS) {
	const pkgDir = join(repoRoot, "node_modules", set.pkg);
	if (!existsSync(join(pkgDir, "icons.json"))) {
		console.error(`error: ${set.pkg} is not installed (expected node_modules/${set.pkg})`);
		process.exit(1);
	}
	collections[set.pkg] = JSON.parse(readFileSync(join(pkgDir, "icons.json"), "utf8"));
}

console.log(`Generating ${SETS.length + 1} icon set modules from ${semanticNames.length} semantic icons…`);
for (const set of SETS) {
	const count = writeCollectionModule(set, semanticNames, mapping, collections);
	console.log(`  ${set.id.padEnd(17)} ${String(count).padStart(3)}/${semanticNames.length} mapped`);
}
const msCount = writeMaterialSymbolsModule(semanticNames, mapping);
console.log(`  ${"material-symbols".padEnd(17)} ${String(msCount).padStart(3)}/${semanticNames.length} mapped`);

let failed = false;
for (const [setId, misses] of missing) {
	if (misses.length === 0) continue;
	const set = SETS.find((entry) => entry.id === setId);
	console.log(`missing in ${setId}:`);
	for (const miss of misses) console.log(`  - ${miss}`);
	if (set?.required) {
		console.error(`error: lucide is the default set — every semantic icon must map to it.`);
		failed = true;
	}
}
if (failed) process.exit(1);
console.log("done.");
